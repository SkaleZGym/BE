-- 관리자 접속기록 (개인정보의 안전성 확보조치 기준 제8조: 1년 이상 보관). 2년 지난 기록은 매일 지운다
create table admin_access_logs (
                                   id          bigint generated by default as identity primary key,
                                   member_id   bigint,                -- 요청한 회원 번호. 로그인 시도처럼 토큰이 없으면 비어 있다
                                   method      varchar(10)  not null,
                                   path        varchar(300) not null,
                                   query       varchar(500),
                                   status      int          not null,
                                   ip          varchar(64)  not null, -- 서버에 직접 붙은 주소 (FE 서버를 거치면 그 주소)
                                   client_ip   varchar(64),           -- FE 서버가 알려 준 실제 접속자 주소
                                   accessed_at timestamp(6) with time zone not null
);
create index idx_admin_access_logs_accessed on admin_access_logs (accessed_at);
create index idx_admin_access_logs_member on admin_access_logs (member_id, id);