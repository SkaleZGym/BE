-- ---------- 할인코드 ----------

create table coupons (
    id                  bigint generated by default as identity primary key,
    code                varchar(30)  not null,     -- 대문자. 예: WELCOME10
    name                varchar(100) not null,
    discount_type       varchar(10)  not null check (discount_type in ('PERCENT', 'FIXED')),
    discount_value      bigint       not null,     -- 정률이면 %, 정액이면 최소 단위 금액
    max_discount_amount bigint,                    -- 정률 할인 상한 (null = 없음)
    min_order_amount    bigint       not null,
    currency            varchar(3)   not null,
    start_at            timestamp(6) with time zone,
    end_at              timestamp(6) with time zone,
    usage_limit         integer,                   -- 전체 사용 횟수 (null = 무제한)
    per_member_limit    integer      not null,
    used_count          integer      not null,
    active              boolean      not null,
    version             bigint       not null,     -- 낙관적 잠금 (마지막 1장 동시 사용 방지)
    created_at          timestamp(6) with time zone not null,
    constraint uk_coupons_code unique (code)
);

-- 주문 하나에 쿠폰 하나. 주문이 취소되면 행을 지운다
create table coupon_redemptions (
    id              bigint generated by default as identity primary key,
    coupon_id       bigint      not null,
    member_id       bigint      not null,
    order_number    varchar(30) not null,
    discount_amount bigint      not null,
    redeemed_at     timestamp(6) with time zone not null,
    constraint uk_coupon_redemptions_order unique (order_number),
    constraint fk_coupon_redemptions_coupon foreign key (coupon_id) references coupons (id)
);
create index idx_coupon_redemptions_coupon_member on coupon_redemptions (coupon_id, member_id);

-- ---------- 배송 설정 ----------

-- 통화당 한 줄. 서버가 뜰 때 비어 있으면 ShippingDataInitializer가 기본값을 넣는다
create table shipping_settings (
    currency          varchar(3) primary key,
    base_fee          bigint  not null,
    free_threshold    bigint,                      -- null = 무료배송 없음
    jeju_extra_fee    bigint  not null,
    island_extra_fee  bigint  not null,
    auto_deliver_days integer not null,
    updated_at        timestamp(6) with time zone not null
);

-- 추가 배송비 지역 (국내 우편번호 범위)
create table remote_areas (
    id       bigint generated by default as identity primary key,
    type     varchar(10) not null check (type in ('JEJU', 'ISLAND')),
    zip_from integer     not null,
    zip_to   integer     not null,
    memo     varchar(100)
);
create index idx_remote_areas_zip on remote_areas (zip_from, zip_to);

-- ---------- 공지사항 · FAQ ----------

create table notices (
    id         bigint generated by default as identity primary key,
    category   varchar(10) not null check (category in ('NOTICE', 'EVENT')),
    pinned     boolean     not null,
    published  boolean     not null,
    view_count bigint      not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);
create index idx_notices_list on notices (published, pinned, created_at);

create table notice_texts (
    notice_id bigint         not null,
    language  varchar(10)    not null,
    title     varchar(200)   not null,
    content   varchar(10000) not null,
    primary key (notice_id, language),
    constraint fk_notice_texts_notice foreign key (notice_id) references notices (id)
);

create table faqs (
    id         bigint generated by default as identity primary key,
    category   varchar(20) not null check (category in ('ORDER', 'SHIPPING', 'EXCHANGE_RETURN', 'PRODUCT', 'MEMBER', 'ETC')),
    sort_order integer     not null,
    published  boolean     not null,
    updated_at timestamp(6) with time zone not null
);
create index idx_faqs_category_sort on faqs (category, sort_order);

create table faq_texts (
    faq_id   bigint         not null,
    language varchar(10)    not null,
    title    varchar(200)   not null,
    content  varchar(10000) not null,
    primary key (faq_id, language),
    constraint fk_faq_texts_faq foreign key (faq_id) references faqs (id)
);
