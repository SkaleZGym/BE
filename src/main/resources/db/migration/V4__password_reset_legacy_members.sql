-- ---------- 회원 ----------

-- 아임웹에서 옮겨 온 회원은 비밀번호를 가져올 수 없어서 비어 있다 (처음 접속 때 메일로 설정)
alter table members alter column password drop not null;
alter table members add column phone varchar(255);                       -- AES-GCM 암호문(Base64)
alter table members add column marketing_consent boolean not null default false;
alter table members add column marketing_consent_at timestamp(6) with time zone;
alter table members add column terms_agreed_at timestamp(6) with time zone;
-- 어디서 옮겨 온 회원인지 (null = 새 사이트에서 가입)
alter table members add column legacy_source varchar(20);
alter table members add constraint ck_members_legacy_source check (legacy_source in ('IMWEB'));
alter table members add column legacy_id varchar(50);

-- ---------- 비밀번호 재설정 링크 ----------

-- 메일 링크의 토큰은 원문 대신 SHA-256 해시만 저장한다 (DB가 새도 링크를 쓸 수 없게)
create table password_reset_tokens (
    id         bigint generated by default as identity primary key,
    member_id  bigint      not null,
    token_hash varchar(64) not null,
    expires_at timestamp(6) with time zone not null,
    used_at    timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    constraint uk_password_reset_tokens_hash unique (token_hash),
    constraint fk_password_reset_tokens_member foreign key (member_id) references members (id)
);
create index idx_password_reset_tokens_member on password_reset_tokens (member_id, created_at);
