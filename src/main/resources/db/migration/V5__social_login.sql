-- V5: 카카오 · 네이버 간편 로그인
-- V1~V4와 같은 규칙: H2(PostgreSQL 모드)·PostgreSQL 공통 문법, 시각은 timestamp with time zone, enum은 varchar + check

-- 회원 한 명에 간편 로그인 계정 여러 개(카카오·네이버)를 이을 수 있다
create table member_social_accounts (
    id               bigint generated by default as identity primary key,
    member_id        bigint       not null,
    provider         varchar(20)  not null check (provider in ('KAKAO', 'NAVER')),
    provider_user_id varchar(100) not null,   -- 카카오 회원번호 · 네이버 고유 id
    created_at       timestamp(6) with time zone not null,
    constraint uk_member_social_accounts_provider_user unique (provider, provider_user_id),
    constraint uk_member_social_accounts_member_provider unique (member_id, provider),
    constraint fk_member_social_accounts_member foreign key (member_id) references members (id)
);

-- 간편 로그인으로 처음 온 사람: 약관 동의를 받을 때까지 잠깐 들고 있는 가입 표 (10분, 한 번 쓰면 끝)
-- 표 원문은 FE 서버의 httpOnly 쿠키에만 있고 DB에는 SHA-256 해시만 둔다
create table social_signup_tickets (
    id               bigint generated by default as identity primary key,
    ticket_hash      varchar(64)  not null,
    provider         varchar(20)  not null check (provider in ('KAKAO', 'NAVER')),
    provider_user_id varchar(100) not null,
    email            varchar(100) not null,
    name             varchar(255),            -- AES-GCM 암호문(Base64)
    expires_at       timestamp(6) with time zone not null,
    used_at          timestamp(6) with time zone,
    created_at       timestamp(6) with time zone not null,
    constraint uk_social_signup_tickets_hash unique (ticket_hash)
);
