-- V3: 상품 후기
-- V1·V2와 같은 규칙: H2(PostgreSQL 모드)·PostgreSQL 공통 문법, 시각은 timestamp with time zone, enum은 varchar + check

create table reviews (
    id           bigint generated by default as identity primary key,
    product_id   bigint        not null,
    member_id    bigint        not null,
    order_number varchar(30)   not null,  -- 어느 배송 완료 주문으로 산 상품인지
    rating       integer       not null check (rating between 1 and 5),
    content      varchar(1000) not null,
    status       varchar(20)   not null check (status in ('VISIBLE', 'HIDDEN')),
    reply        varchar(1000),           -- 관리자 답글
    replied_at   timestamp(6) with time zone,
    created_at   timestamp(6) with time zone not null,
    -- 회원당 상품 하나에 후기 하나
    constraint uk_reviews_member_product unique (member_id, product_id),
    constraint fk_reviews_product foreign key (product_id) references products (id),
    constraint fk_reviews_member foreign key (member_id) references members (id)
);
-- 상품 상세의 후기 목록 (노출 중인 것만, 최신순)
create index idx_reviews_product_status_created on reviews (product_id, status, created_at);
create index idx_reviews_status_created on reviews (status, created_at);
