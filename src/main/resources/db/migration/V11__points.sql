-- V11: 적립금
-- 회원별 잔액은 members.point_balance 에 두고, 늘고 준 기록은 point_histories 에 한 줄씩 남긴다 (기록을 다 더하면 잔액)
alter table members add column point_balance bigint not null default 0;

-- 주문에 쓴 적립금 / 배송 완료 때 준 적립금
alter table orders add column points_used bigint not null default 0;
alter table orders add column points_earned bigint not null default 0;

create table point_histories (
    id            bigint generated by default as identity primary key,
    member_id     bigint       not null references members (id),
    type          varchar(20)  not null check (type in ('EARN', 'USE', 'USE_CANCEL', 'EARN_CANCEL', 'ADMIN', 'MIGRATION')),
    amount        bigint       not null, -- 늘면 +, 줄면 -
    balance_after bigint       not null, -- 이 기록 뒤 잔액
    order_number  varchar(30),
    memo          varchar(200),
    created_at    timestamp(6) with time zone not null
);
create index idx_point_histories_member on point_histories (member_id, id);
