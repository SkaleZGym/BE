-- V7: 교환·반품 신청
-- V1~V6과 같은 규칙: H2(PostgreSQL 모드)·PostgreSQL 공통 문법, 시각은 timestamp with time zone, enum은 varchar + check

create table order_claims (
                              id              bigint generated by default as identity primary key,
                              order_id        bigint        not null,
                              member_id       bigint        not null,
                              type            varchar(20)   not null check (type in ('EXCHANGE', 'RETURN')),
                              reason          varchar(20)   not null check (reason in ('SIZE', 'DEFECT', 'WRONG_ITEM', 'CHANGE_OF_MIND', 'OTHER')),
                              detail          varchar(1000),
                              status          varchar(20)   not null check (status in ('REQUESTED', 'APPROVED', 'REJECTED', 'COMPLETED')),
                              admin_memo      varchar(1000),           -- 고객에게도 보이는 처리 안내 (거절 사유 등)
                              refund_amount   bigint,                  -- 반품 완료 때 실제 환불한 금액
                              courier         varchar(20),             -- 교환 상품을 다시 보낸 택배사
                              tracking_number varchar(50),
                              created_at      timestamp(6) with time zone not null,
                              processed_at    timestamp(6) with time zone, -- 승인·거절한 시각
                              completed_at    timestamp(6) with time zone,
                              constraint fk_order_claims_order foreign key (order_id) references orders (id),
                              constraint fk_order_claims_member foreign key (member_id) references members (id)
);
create index idx_order_claims_order on order_claims (order_id);
create index idx_order_claims_member_created on order_claims (member_id, created_at);
create index idx_order_claims_status_created on order_claims (status, created_at);

-- 신청에 들어간 주문 상품 (교환이면 바꿀 사이즈도)
create table order_claim_items (
                                   claim_id      bigint      not null,
                                   order_item_id bigint      not null,
                                   quantity      integer     not null check (quantity > 0),
                                   exchange_size varchar(10),
                                   constraint fk_order_claim_items_claim foreign key (claim_id) references order_claims (id),
                                   constraint fk_order_claim_items_item foreign key (order_item_id) references order_items (id)
);
create index idx_order_claim_items_claim on order_claim_items (claim_id);