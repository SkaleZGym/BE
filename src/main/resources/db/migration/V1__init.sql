-- SKALEZ 초기 스키마. 엔티티(com.skalez.*.domain)와 1:1로 맞춘다 (서버가 뜰 때 Hibernate가 validate 로 대조).
-- 로컬 H2(PostgreSQL 모드)와 운영 PostgreSQL 양쪽에서 그대로 실행되는 문법만 쓴다.
-- 시각은 모두 UTC(timestamp with time zone), 금액은 최소 단위 정수(bigint: 원·센트).
-- enum 컬럼은 varchar + check 로 저장한다. 값이 늘면 새 마이그레이션에서 check 제약을 바꿔야 한다.

-- ---------- 회원 ----------

create table members (
    id         bigint generated by default as identity primary key,
    email      varchar(100) not null,
    password   varchar(255) not null,              -- {bcrypt} 해시
    name       varchar(255) not null,              -- AES-GCM 암호문(Base64)
    role       varchar(20)  not null check (role in ('USER', 'ADMIN')),
    status     varchar(20)  not null check (status in ('ACTIVE', 'SUSPENDED')),
    language   varchar(10)  not null,              -- ko, en, ja, zh-CN
    created_at timestamp(6) with time zone not null,
    constraint uk_members_email unique (email)
);

-- ---------- 카테고리 ----------

create table categories (
    id         bigint generated by default as identity primary key,
    code       varchar(50) not null,               -- MEN, MEN_TOP ...
    parent_id  bigint,                             -- 최상위면 null. 2단계까지만 쓴다
    sort_order integer     not null,
    constraint uk_categories_code unique (code),
    constraint fk_categories_parent foreign key (parent_id) references categories (id)
);
create index idx_categories_parent on categories (parent_id);

create table category_names (
    category_id bigint       not null,
    language    varchar(10)  not null,
    name        varchar(100) not null,
    primary key (category_id, language),
    constraint fk_category_names_category foreign key (category_id) references categories (id)
);

-- ---------- 상품 ----------

create table products (
    id          bigint generated by default as identity primary key,
    sku         varchar(50) not null,
    category_id bigint      not null,
    status      varchar(20) not null check (status in ('ON_SALE', 'HIDDEN')),
    image_url   varchar(500),
    created_at  timestamp(6) with time zone not null,
    constraint uk_products_sku unique (sku),
    constraint fk_products_category foreign key (category_id) references categories (id)
);
create index idx_products_category on products (category_id);
create index idx_products_status_created on products (status, created_at);

-- 통화별 가격 (KRW, USD). list_amount 는 할인 전 가격(없으면 null)
create table product_prices (
    product_id  bigint     not null,
    currency    varchar(3) not null,
    amount      bigint     not null,
    list_amount bigint,
    primary key (product_id, currency),
    constraint fk_product_prices_product foreign key (product_id) references products (id)
);

create table product_badges (
    product_id bigint      not null,
    badge      varchar(20) not null check (badge in ('NEW', 'SALE', 'BEST', 'HOT')),
    constraint uk_product_badges unique (product_id, badge),
    constraint fk_product_badges_product foreign key (product_id) references products (id)
);

create table product_translations (
    id          bigint generated by default as identity primary key,
    product_id  bigint       not null,
    language    varchar(10)  not null,
    name        varchar(200) not null,
    description varchar(2000),
    constraint uk_product_translations unique (product_id, language),
    constraint fk_product_translations_product foreign key (product_id) references products (id)
);

-- 사이즈별 옵션·재고. version 은 동시 주문 시 재고 충돌을 막는 낙관적 락 값
create table product_variants (
    id         bigint generated by default as identity primary key,
    product_id bigint      not null,
    size       varchar(10) not null,
    stock      integer     not null,
    sort_order integer     not null,
    version    bigint      not null,
    constraint uk_product_variants unique (product_id, size),
    constraint fk_product_variants_product foreign key (product_id) references products (id)
);

-- ---------- 장바구니 · 찜 ----------

create table cart_items (
    id         bigint generated by default as identity primary key,
    member_id  bigint  not null,
    variant_id bigint  not null,
    quantity   integer not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_cart_items unique (member_id, variant_id),
    constraint fk_cart_items_variant foreign key (variant_id) references product_variants (id)
);

create table wish_items (
    id         bigint generated by default as identity primary key,
    member_id  bigint not null,
    product_id bigint not null,
    created_at timestamp(6) with time zone not null,
    constraint uk_wish_items unique (member_id, product_id),
    constraint fk_wish_items_product foreign key (product_id) references products (id)
);

-- ---------- 주문 ----------

create table orders (
    id              bigint generated by default as identity primary key,
    order_number    varchar(30) not null,          -- 예: 20261020-3F9A1C2B
    member_id       bigint      not null,
    status          varchar(20) not null check (status in ('PENDING_PAYMENT', 'PAID', 'PREPARING', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    currency        varchar(3)  not null,
    items_amount    bigint      not null,
    shipping_fee    bigint      not null,
    total_amount    bigint      not null,
    -- 배송지. country_code 외에는 AES-GCM 암호문이라 원문보다 길다
    recipient       varchar(255) not null,
    phone           varchar(255) not null,
    country_code    varchar(2)   not null,
    postal_code     varchar(255) not null,
    address1        varchar(500) not null,
    address2        varchar(500),
    payment_id      varchar(100),                  -- PG 결제 ID (나이스페이 tid)
    tracking_number varchar(50),
    created_at      timestamp(6) with time zone not null,
    paid_at         timestamp(6) with time zone,
    shipped_at      timestamp(6) with time zone,
    constraint uk_orders_order_number unique (order_number)
);
create index idx_orders_member_created on orders (member_id, created_at);
create index idx_orders_status_created on orders (status, created_at);

-- 주문 당시 상품명·단가를 그대로 남긴다 (상품이 바뀌어도 주문 내역은 유지)
create table order_items (
    id           bigint generated by default as identity primary key,
    order_id     bigint       not null,
    product_id   bigint       not null,
    variant_id   bigint       not null,
    product_name varchar(200) not null,
    size         varchar(10)  not null,
    unit_price   bigint       not null,
    quantity     integer      not null,
    constraint fk_order_items_order foreign key (order_id) references orders (id)
);
create index idx_order_items_order on order_items (order_id);

-- ---------- 1:1 문의 ----------

create table inquiries (
    id           bigint generated by default as identity primary key,
    member_id    bigint        not null,
    category     varchar(20)   not null check (category in ('PRODUCT', 'ORDER', 'DELIVERY', 'EXCHANGE_RETURN', 'ETC')),
    title        varchar(100)  not null,
    content      varchar(2000) not null,
    product_id   bigint,
    order_number varchar(30),
    status       varchar(20)   not null check (status in ('WAITING', 'ANSWERED')),
    answer       varchar(2000),
    answered_at  timestamp(6) with time zone,
    created_at   timestamp(6) with time zone not null
);
create index idx_inquiries_member_created on inquiries (member_id, created_at);
create index idx_inquiries_status_created on inquiries (status, created_at);

-- ---------- 배너 · 사이트 문구 ----------

create table banners (
    id         bigint generated by default as identity primary key,
    position   varchar(20)  not null check (position in ('MAIN_HERO', 'MAIN_SUB', 'POPUP')),
    image_url  varchar(500) not null,
    link_url   varchar(500),
    sort_order integer      not null,
    active     boolean      not null,
    start_at   timestamp(6) with time zone,
    end_at     timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null
);
create index idx_banners_position_sort on banners (position, sort_order);

create table banner_texts (
    banner_id bigint      not null,
    language  varchar(10) not null,
    headline  varchar(200),
    subtext   varchar(500),
    primary key (banner_id, language),
    constraint fk_banner_texts_banner foreign key (banner_id) references banners (id)
);

create table site_texts (
    id          bigint generated by default as identity primary key,
    text_key    varchar(100) not null,             -- 예: home.hero.headline
    description varchar(200),
    updated_at  timestamp(6) with time zone not null,
    constraint uk_site_texts_key unique (text_key)
);

create table site_text_values (
    site_text_id bigint      not null,
    language     varchar(10) not null,
    text_value   varchar(2000),
    primary key (site_text_id, language),
    constraint fk_site_text_values_site_text foreign key (site_text_id) references site_texts (id)
);
