-- V10: 아임웹에서 옮겨 온 데이터
-- 1) 이전 주문: 새 주문 흐름(결제·배송·교환)과 섞지 않고, 회원이 마이페이지에서 '이전 쇼핑몰 주문'으로 보기만 한다
create table legacy_orders (
    id                  bigint generated by default as identity primary key,
    source              varchar(20)   not null,   -- IMWEB
    legacy_order_number varchar(50)   not null,
    email               varchar(100),             -- 주문자 이메일 (소문자). 회원 이메일로 마이페이지와 이어진다
    ordered_at          timestamp(6) with time zone,
    status_text         varchar(50),              -- 아임웹 주문 상태 글자 그대로
    items_text          varchar(2000) not null,   -- '상품명 / 옵션 × 수량' 줄들
    total_amount        bigint,
    currency            varchar(3)    not null,
    imported_at         timestamp(6) with time zone not null,
    constraint uk_legacy_orders_number unique (source, legacy_order_number)
);
create index idx_legacy_orders_email on legacy_orders (email, ordered_at);

-- 2) 이전 후기: 회원·주문이 없을 수 있어 비워 둘 수 있게 하고, 작성자 이름과 원본 번호를 둔다
alter table reviews alter column member_id drop not null;
alter table reviews alter column order_number drop not null;
alter table reviews add column author_name varchar(50);
alter table reviews add column legacy_source varchar(20);
alter table reviews add column legacy_id varchar(50);
create unique index uk_reviews_legacy on reviews (legacy_source, legacy_id);
